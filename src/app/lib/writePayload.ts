/** Converts domain payloads to the actual stored schema. RLS remains the authority. */
export async function writePayload(table: string,input: Record<string,unknown>): Promise<Record<string,unknown>> {
  const source={...input};
  if(source.performed_by_user_id) source.performed_by=source.performed_by_user_id;
  if(columns[table]?.includes('branch_id') && !source.branch_id && typeof source.branch==='string' && source.branch && source.branch!=='Tüm Şubeler') {
    const {data,error}=await supabase.from('branches').select('id').eq('name',source.branch).single();
    if(error || !data) throw new Error('Şube adı tek bir yetkili şubeyle eşleşmelidir.');
    source.branch_id=data.id;
  }
  if(table==='branches' && source.status) source.status=source.status==='Aktif'?'active':source.status==='Pasif'?'inactive':source.status;
  return Object.fromEntries(Object.entries(source).filter(([key])=>columns[table]?.includes(key) && !['id','organization_id','created_at','updated_at'].includes(key)).map(([key,value])=>[key,value==='' && (key.endsWith('_date') || key.endsWith('_expiry') || key==='last_visit' || key==='birth_date')?null:value]));
}
